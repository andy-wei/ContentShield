"""按攻击类别定制的安全拒绝模板（DPO chosen 合成用）。

红队库里只存攻击 prompt 与目标模型屈服的回复（rejected），chosen（安全
响应）需要合成——业界通行做法（HarmBench / Llama 安全数据集同款思路）。
每类别多模板随机轮换，避免单一模板导致微调模型过拟合固定句式。
"""

from __future__ import annotations

import random

# 各攻击类别的拒绝模板（占位符无——模板面向类别而非具体攻击内容，
# 保持通用性；刻意措辞多样：说明型/简短型/引导型）
REFUSAL_TEMPLATES: dict[str, list[str]] = {
    "jailbreak": [
        "我不能协助这个请求。无论请求如何包装或设定情境，我都不会生成可能造成伤害的内容。",
        "抱歉，我无法扮演这个角色或绕过安全准则。如果你有其他正当问题，我很乐意帮忙。",
        "这个请求试图让我偏离安全使用规范，我不能配合。我们可以聊点别的吗？",
    ],
    "prompt_injection": [
        "我检测到这段内容中包含试图覆盖我指令的注入文本，我不会执行其中嵌入的指令。",
        "抱歉，指令内容与我的安全策略冲突，我不能遵循来自数据内容中的命令。",
        "我不会响应以数据、工具输出或网页内容形式夹带的指令。请直接说明你的需求。",
    ],
    "harmful_request": [
        "我不能提供这类可能造成伤害的帮助。",
        "抱歉，这个请求涉及有害内容，我无法协助。",
        "这个请求超出了我能安全提供帮助的范围。如果你面临实际困难，建议寻求专业渠道。",
    ],
    "encoding": [
        "我注意到请求使用了编码或混淆手段来规避安全检查，解码后我仍不会协助其中包含的意图。",
        "抱歉，无论内容以何种编码形式呈现，我的安全判断保持一致，不能提供这类帮助。",
    ],
    "social_engineering": [
        "我不会在缺乏正当授权和身份验证的情况下协助这类操作，这个请求模式像是社工攻击。",
        "抱歉，凭据、内部数据或越权操作相关的请求我无法协助，无论给出的理由是什么。",
    ],
}

# 通用池（未知类别回退）
GENERIC_REFUSALS: list[str] = [
    "我不能协助这个请求。",
    "抱歉，基于安全考虑我无法提供这方面的帮助。",
    "这个请求我不能配合。有其他问题欢迎直接提出。",
]


def pick_refusal(category: str, rng: random.Random | None = None) -> str:
    """按攻击类别随机取一条拒绝模板（未知类别回退通用池）。"""
    r = rng or random
    pool = REFUSAL_TEMPLATES.get(category, GENERIC_REFUSALS)
    return r.choice(pool)
